/**
 * Convert Traditional Chinese text to Simplified Chinese.
 * Characters not found in the mapping table pass through unchanged.
 */
function t2s(text) {
  if (!text) return '';
  var result = '';
  for (var i = 0; i < text.length; i++) {
    var ch = text[i];
    var mapped = T2S_MAP[ch];
    result += (mapped !== undefined) ? mapped : ch;
  }
  return result;
}
